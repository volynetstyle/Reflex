import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { protocolManifest } from "./protocol.mjs";
import { transplantProtocol } from "./migrate-protocol.mjs";
import { options, required, writeJson } from "./io.mjs";
const opts=options(process.argv.slice(2),["--base-root","--head-root","--entries","--output-dir"]);
const baseRoot=resolve(required(opts,"base-root")),headRoot=resolve(required(opts,"head-root")),output=resolve(required(opts,"output-dir"));
const entries=required(opts,"entries").split(",").filter(Boolean);
mkdirSync(output,{recursive:true});
const before=protocolManifest(baseRoot,entries),head=protocolManifest(headRoot,entries);
const evidencePath=join(output,"config-equivalence.json");
const parity=spawnSync(process.execPath,[fileURLToPath(new URL("../configs/check-equivalence.mjs",import.meta.url)),"--baseline-root",baseRoot,"--head-root",headRoot,"--output",evidencePath],{cwd:headRoot,encoding:"utf8",windowsHide:true});
if(parity.status!==0)throw new Error("Benchmark protocol migration requires resolved config parity.\n"+parity.stdout+parity.stderr);
const migration=transplantProtocol({baseRoot,headRoot,entries,configEvidence:JSON.parse(readFileSync(evidencePath,"utf8"))});
if(protocolManifest(baseRoot,entries).protocolHash!==head.protocolHash)throw new Error("Migrated protocol does not match head");
writeJson(join(output,"protocol.json"),{...head,compatible:true});
writeJson(join(output,"migration.json"),migration);
console.log(JSON.stringify({protocolHash:head.protocolHash,baselineMigration:before.protocolHash!==head.protocolHash}));
